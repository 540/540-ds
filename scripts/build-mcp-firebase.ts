/**
 * Packs the Firebase function into firebase/functions/: one ESM file with the MCP server and its
 * metadata inside, plus a minimal package.json. Firebase deploys that folder, never the whole repo.
 *
 *   npm run build:firebase      (builds the metadata with --strict first)
 *
 * firebase-functions and firebase-admin stay outside the bundle and get installed in the folder:
 * the Firebase CLI loads them locally to discover the function before deploying it.
 */
import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'firebase', 'functions');
const NODE_MAJOR = '24';

const installedVersion = (pkg: string) => JSON.parse(fs.readFileSync(path.join(root, 'node_modules', pkg, 'package.json'), 'utf-8')).version as string;

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const result = await build({
  entryPoints: [path.join(root, 'mcp', 'firebase.ts')],
  outfile: path.join(outDir, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: `node${NODE_MAJOR}`,
  external: ['firebase-functions', 'firebase-functions/*', 'firebase-admin', 'firebase-admin/*'],
  // Some bundled CommonJS dependencies call require(): give the ESM bundle one.
  banner: { js: "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
  legalComments: 'none',
  metafile: true,
  logLevel: 'warning',
});

const pkg = {
  name: '540-ds-mcp-functions',
  private: true,
  description: 'Generated by scripts/build-mcp-firebase.ts. Do not edit.',
  type: 'module',
  main: 'index.js',
  engines: { node: NODE_MAJOR },
  dependencies: {
    'firebase-functions': installedVersion('firebase-functions'),
    'firebase-admin': installedVersion('firebase-admin'),
  },
};
fs.writeFileSync(path.join(outDir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);

execSync('npm install --omit=dev --no-audit --no-fund --loglevel=error', { cwd: outDir, stdio: 'inherit' });

const kb = Math.round(Object.values(result.metafile.outputs)[0].bytes / 1024);
console.log(`✓ firebase/functions/index.js (${kb} KB), Node ${NODE_MAJOR}, firebase-functions ${pkg.dependencies['firebase-functions']}`);
